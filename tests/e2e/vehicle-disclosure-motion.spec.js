const { test, expect } = require('@playwright/test');

test('vehicle palette and trailer field expand, reverse and respect reduced motion', async ({ page }) => {
  test.setTimeout(120_000);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('/dev-login/user');
  await page.goto('/vehicles/new');
  const picker = page.locator('.vehicle-color-picker');
  const toggle = page.locator('.vehicle-color-toggle');
  const panel = page.locator('.vehicle-color-panel');
  const trailer = page.locator('[data-tractor]');
  const kind = page.getByLabel('Тип', { exact: true });
  const collapsedHeight = (await picker.boundingBox()).height;
  await toggle.click();
  await expect(toggle).toHaveAttribute('aria-expanded', 'true');
  await expect.poll(async () => (await picker.boundingBox()).height).toBeGreaterThan(collapsedHeight + 70);
  await expect(picker).not.toHaveClass(/vehicle-revealing/);
  await toggle.click();
  await expect(panel).toBeHidden();
  expect(Math.abs((await picker.boundingBox()).height - collapsedHeight)).toBeLessThan(1);
  // Reverse running animations without leaving a fixed height or stale state.
  await toggle.click();
  await toggle.click();
  await toggle.click();
  await expect(toggle).toHaveAttribute('aria-expanded', 'true');
  await expect(picker).not.toHaveClass(/vehicle-revealing/);
  await expect(panel).toBeVisible();
  await toggle.press('Escape');
  await expect(panel).toBeHidden();
  await expect(trailer).toBeHidden();
  await kind.selectOption('tractor_unit');
  await expect(trailer).toBeVisible();
  await expect(trailer).not.toHaveClass(/vehicle-revealing/);
  await page.getByLabel('Название прицепа', { exact: true }).fill('Учебный прицеп анимации');
  await kind.selectOption('passenger');
  expect(await page.locator('form.vehicle-form').evaluate(form => new FormData(form).has('trailer_name'))).toBe(false);
  await kind.selectOption('tractor_unit');
  await expect(trailer).not.toHaveClass(/vehicle-revealing/);
  await expect(page.getByLabel('Название прицепа', { exact: true })).toHaveValue('Учебный прицеп анимации');
  expect(await page.locator('form.vehicle-form').evaluate(form => new FormData(form).get('trailer_name'))).toBe('Учебный прицеп анимации');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await kind.selectOption('passenger');
  await expect(trailer).toBeHidden();
  await kind.selectOption('tractor_unit');
  await expect(trailer).toBeVisible();
  expect(await trailer.evaluate(element => element.getAnimations().length)).toBe(0);
  await toggle.click();
  await expect(panel).toBeVisible();
  expect(await picker.evaluate(element => element.getAnimations().length)).toBe(0);
  await toggle.click();
  await expect(panel).toBeHidden();
});
